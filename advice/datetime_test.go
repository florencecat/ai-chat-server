package advice

import "testing"

func TestLocalDateTime(t *testing.T) {
	tests := []struct {
		in   string
		want string
	}{
		// Обозначение пояса отбрасывается, а не пересчитывается: модель ставит
		// стенные часы пользователя и помечает их «Z».
		{"2026-07-19T10:00:00Z", "2026-07-19T10:00:00"},
		{"2026-07-19T10:00:00+03:00", "2026-07-19T10:00:00"},
		{"2026-07-19T10:00:00", "2026-07-19T10:00:00"},
		{"2026-07-19T10:00", "2026-07-19T10:00:00"},
		{"2026-07-19 10:00", "2026-07-19T10:00:00"},
		{"2026-07-19t10:00:00z", "2026-07-19T10:00:00"},
		{"2026-07-19", "2026-07-19T00:00:00"},
		{"  2026-07-19T08:30:15Z  ", "2026-07-19T08:30:15"},
		{"завтра утром", ""},
		{"", ""},
		{"19.07.2026 10:00", ""},
	}
	for _, tc := range tests {
		if got := localDateTime(tc.in); got != tc.want {
			t.Errorf("localDateTime(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}
