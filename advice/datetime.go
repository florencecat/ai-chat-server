package advice

import (
	"regexp"
	"strings"
)

// dateTimeRe вытаскивает стенные часы из чего угодно, похожего на ISO-8601:
// дата обязательна, время — нет, обозначение пояса в группы не попадает.
var dateTimeRe = regexp.MustCompile(
	`^(\d{4}-\d{2}-\d{2})(?:[Tt ](\d{2}:\d{2})(?::(\d{2}))?)?`,
)

// localDateTime приводит datetime от модели к местному времени пользователя в
// формате YYYY-MM-DDTHH:MM:SS — без «Z» и без смещения.
//
// Обозначение пояса именно отбрасывается, а не пересчитывается: модель ставит
// стенные часы пользователя и помечает их суффиксом «Z», будто это UTC
// (на «напомни сегодня в 10:00» приходит 2026-07-19T10:00:00Z). Разбор как
// настоящего UTC унёс бы напоминание на величину смещения. Клиент поступает
// так же (parseAiDateTime), поэтому сервер и клиент дают одинаковый результат.
//
// Пустая строка означает «время разобрать не удалось».
func localDateTime(s string) string {
	m := dateTimeRe.FindStringSubmatch(strings.TrimSpace(s))
	if m == nil {
		return ""
	}
	date, clock, sec := m[1], m[2], m[3]
	if clock == "" {
		clock = "00:00"
	}
	if sec == "" {
		sec = "00"
	}
	return date + "T" + clock + ":" + sec
}
